say_mp3 0038 "我不催你，你自己决定什么时候开始。"
say_mp3 0039 "你做完没做完，妈妈都爱你。"
say_mp3 0040 "明天我们继续，慢慢来。"

rm -f tmp.aiff
echo "完成：$(ls -1 *.mp3 | wc -l | tr -d ' ') 个文件，共 $(du -sh . | cut -f1)"
