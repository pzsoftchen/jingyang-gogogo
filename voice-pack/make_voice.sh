# ---------- 0501~0503 完成音效（1.85 走 I2S；DevKitC 用蜂鸣器）----------
chime() {  # $1=文件名  $2=ffmpeg 参数  $3=滤镜
  ffmpeg -y -loglevel error $2 -filter_complex "$3" -ar 22050 -ac 1 -b:a 32k "$1.mp3"
}
